export function buildCorpusSeedList(): CorpusSeedEntry[] {
  const seen = new Set<string>();
  const all: CorpusSeedEntry[] = [];

  const pushUnique = (lemma: string, language: 'fr' | 'de', cefrLevel: CorpusCefrLevel, partOfSpeech: string) => {
    const clean = lemma.toLowerCase().trim();
    const key = `${language}:${clean}`;
    if (!clean || seen.has(key)) return;
    seen.add(key);
    all.push({ lemma: clean, language, cefrLevel, partOfSpeech });
  };

  for (const [w, pos] of FR_B1_WORDS) pushUnique(w, 'fr', 'B1', pos);
  for (const [w, pos] of FR_B2_WORDS) pushUnique(w, 'fr', 'B2', pos);
  for (const [w, pos, lvl] of FR_C1_C2_WORDS) pushUnique(w, 'fr', lvl, pos);
  for (const [w, pos, lvl] of DE_B1_B2_C1_C2_WORDS) pushUnique(w, 'de', lvl, pos);

  return all;
}

/**
 * Peuple la table PostgreSQL CorpusLexicon (B1–C2) de manière idempotente
 */
export async function seedCorpusLexicon(prisma: PrismaClient): Promise<number> {
  const entries = buildCorpusSeedList();
  const result = await prisma.corpusLexicon.createMany({
    data: entries,
    skipDuplicates: true,
  });
  return result.count;
}
